import fs from 'node:fs';
import path from 'node:path';
import type { GeneratedFile } from '@aiui/shared';
import { config } from '../config.ts';
import { type BuildPlan, describeFlow, envExample, safeName } from './index.ts';

/** Render a JSON value as a readable Python literal. */
export function toPython(value: unknown, indent = 0): string {
  const pad = '    '.repeat(indent);
  const inner = '    '.repeat(indent + 1);
  if (value === null || value === undefined) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'None';
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const flat = `[${value.map((v) => toPython(v, 0)).join(', ')}]`;
    if (flat.length <= 80 && !flat.includes('\n')) return flat;
    return `[\n${value.map((v) => `${inner}${toPython(v, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  if (entries.length === 0) return '{}';
  const flat = `{${entries.map(([k, v]) => `${JSON.stringify(k)}: ${toPython(v, 0)}`).join(', ')}}`;
  if (flat.length <= 80 && !flat.includes('\n')) return flat;
  return `{\n${entries.map(([k, v]) => `${inner}${JSON.stringify(k)}: ${toPython(v, indent + 1)},`).join('\n')}\n${pad}}`;
}

const moduleName = (type: string) => type.replace(/[^A-Za-z0-9]+/g, '_');

export function generatePython(built: BuildPlan): GeneratedFile[] {
  const { project } = built;
  const files: GeneratedFile[] = [];
  const title = project.name.replace(/"/g, "'");

  files.push({
    path: 'main.py',
    content: `"""${title} - generated by AIUI.

Run:    python main.py
Help:   see README.md
"""
import os

from aiui_runtime import Workflow, run_cli
from workflow import EDGES, NODES, STEPS

if __name__ == "__main__":
    run_cli(Workflow(NODES, EDGES, STEPS, base_dir=os.path.dirname(os.path.abspath(__file__))))
`,
  });

  const modules = built.types.map((t) => moduleName(t.def.type));
  const imports = modules.length ? `from steps import ${modules.join(', ')}\n\n` : '';
  const steps = built.types.map((t) => `    ${JSON.stringify(t.def.type)}: ${moduleName(t.def.type)}.run,`).join('\n');
  const nodes = built.nodes.map((node) => {
    const definition: Record<string, unknown> = { id: node.id, name: node.name, type: node.type, kind: node.kind, config: node.config };
    if (node.onError === 'continue') definition.onError = 'continue';
    if (node.tool) definition.tool = node.tool;
    return definition;
  });
  files.push({
    path: 'workflow.py',
    content: `"""${title} - the workflow itself: which steps exist and how they are linked.

Generated by AIUI. Change the project in the IDE and export again rather than editing by hand.
"""
${imports}# The code behind each kind of step.
STEPS = {
${steps}
}

# Every step in the project, with its settings. {{name.field}} reads another step's result.
NODES = ${toPython(nodes)}

# Links between steps: when "source" finishes on "sourcePort", "target" runs.
EDGES = ${toPython(built.edges)}
`,
  });

  files.push({ path: 'steps/__init__.py', content: '"""One module per kind of step used in this project."""\n' });
  const requirements = new Set<string>();
  for (const { def } of built.types) {
    files.push({ path: `steps/${moduleName(def.type)}.py`, content: def.codegen.python.source.replace(/\r\n/g, '\n') });
    for (const requirement of def.codegen.python.requirements ?? []) requirements.add(requirement);
  }
  if (built.usesAnthropic) requirements.add('anthropic');

  files.push({ path: 'aiui_runtime.py', content: fs.readFileSync(path.join(config.runtimeDir, 'python', 'aiui_runtime.py'), 'utf8').replace(/\r\n/g, '\n') });
  files.push({ path: 'connections.json', content: JSON.stringify(built.connectionsFile, null, 2) + '\n' });
  files.push({ path: '.env.example', content: envExample(built) });
  files.push({ path: '.gitignore', content: '.env\n__pycache__/\n*.pyc\n.venv/\n' });
  files.push({
    path: 'requirements.txt',
    content: requirements.size
      ? [...requirements].sort().join('\n') + '\n'
      : '# No packages needed - this project uses only the Python standard library.\n',
  });

  const hasSecrets = Object.keys(built.secretEnv).length > 0;
  files.push({
    path: 'README.md',
    content: `# ${project.name}

${project.description ? project.description + '\n\n' : ''}Generated by AIUI. Requires Python 3.10 or newer.

## Run

\`\`\`bash
${requirements.size ? 'pip install -r requirements.txt\n' : ''}${hasSecrets ? 'cp .env.example .env   # then fill in the secrets\n' : ''}python main.py
\`\`\`

| Option | Meaning |
|---|---|
| \`--once\` | Run a single time and exit, whatever the trigger is |
| \`--input '{"key": "value"}'\` | Data for the trigger (or \`--input @file.json\`) |
| \`--events\` | Print machine-readable events instead of log lines |

## Steps

${describeFlow(built)}

## Files

| File | Purpose |
|---|---|
| \`workflow.py\` | The steps, their settings and how they are linked |
| \`steps/\` | The code behind each kind of step |
| \`aiui_runtime.py\` | The engine that runs the workflow |
| \`connections.json\` | Connection settings; secrets are read from the environment |
| \`.env.example\` | The secrets this project needs |
`,
  });
  return files;
}

export const pythonProjectFolder = (name: string) => safeName(name, 'snake');
