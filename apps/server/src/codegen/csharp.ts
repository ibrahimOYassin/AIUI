import fs from 'node:fs';
import path from 'node:path';
import type { GeneratedFile } from '@aiui/shared';
import { config } from '../config.ts';
import { type BuildPlan, describeFlow, envExample, safeName } from './index.ts';

/** Version of the official Anthropic NuGet package referenced when a Claude connection is used. */
const ANTHROPIC_NUGET_VERSION = '13.12.0';

const csString = (text: string) => JSON.stringify(text);

export function generateCSharp(built: BuildPlan): GeneratedFile[] {
  const { project } = built;
  const files: GeneratedFile[] = [];
  const assembly = safeName(project.name, 'pascal');
  const runtime = (file: string) => fs.readFileSync(path.join(config.runtimeDir, 'csharp', file), 'utf8').replace(/\r\n/g, '\n');

  files.push({
    path: 'Program.cs',
    content: `// ${project.name} - generated by AIUI.
// Run:  dotnet run            Help: see README.md

using Aiui.Generated;
using Aiui.Runtime;

// "dotnet run" starts in the project folder; a published build starts next to its files.
var baseDir = File.Exists(Path.Combine(Directory.GetCurrentDirectory(), "connections.json"))
    ? Directory.GetCurrentDirectory()
    : AppContext.BaseDirectory;
${built.usesAnthropic ? '\nAnthropicChat.Register(); // Claude, through the official Anthropic SDK\n' : ''}
var workflow = new Workflow(WorkflowDefinition.Json, WorkflowDefinition.Steps, baseDir);
return await Cli.RunAsync(workflow, args);
`,
  });

  const nodes = built.nodes.map((node) => {
    const definition: Record<string, unknown> = { id: node.id, name: node.name, type: node.type, kind: node.kind, config: node.config };
    if (node.onError === 'continue') definition.onError = 'continue';
    if (node.tool) definition.tool = node.tool;
    return definition;
  });
  const definition = JSON.stringify({ nodes, edges: built.edges }, null, 2);
  const steps = built.types.map((t) => `        [${csString(t.def.type)}] = ${t.def.codegen.csharp.className}.RunAsync,`).join('\n');
  files.push({
    path: 'Workflow.cs',
    content: `// ${project.name} - the workflow itself: which steps exist and how they are linked.
// Generated by AIUI. Change the project in the IDE and export again rather than editing by hand.

using Aiui.Runtime;
using Aiui.Steps;

namespace Aiui.Generated;

public static class WorkflowDefinition
{
    /// <summary>The code behind each kind of step.</summary>
    public static readonly Dictionary<string, StepFunc> Steps = new()
    {
${steps}
    };

    /// <summary>
    /// Every step with its settings, and the links between them.
    /// {{name.field}} reads another step's result.
    /// </summary>
    public const string Json = """"
${definition}
"""";
}
`,
  });

  const packages = new Map<string, string>();
  for (const { def } of built.types) {
    files.push({ path: `Steps/${def.codegen.csharp.className}.cs`, content: def.codegen.csharp.source.replace(/\r\n/g, '\n') });
    for (const pkg of def.codegen.csharp.packages ?? []) packages.set(pkg.name, pkg.version);
  }
  files.push({ path: 'Runtime/AiuiRuntime.cs', content: runtime('AiuiRuntime.cs') });
  if (built.usesAnthropic) {
    files.push({ path: 'Runtime/AnthropicChat.cs', content: runtime('AnthropicChat.cs') });
    packages.set('Anthropic', ANTHROPIC_NUGET_VERSION);
  }

  const references = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b))
    .map(([name, version]) => `    <PackageReference Include="${name}" Version="${version}" />`).join('\n');
  files.push({
    path: `${assembly}.csproj`,
    content: `<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net8.0</TargetFramework>
    <RollForward>Major</RollForward>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <AssemblyName>${assembly}</AssemblyName>
    <RootNamespace>Aiui.Generated</RootNamespace>
    <InvariantGlobalization>true</InvariantGlobalization>
  </PropertyGroup>
${references ? `\n  <ItemGroup>\n${references}\n  </ItemGroup>\n` : ''}
  <ItemGroup>
    <None Update="connections.json" CopyToOutputDirectory="PreserveNewest" />
    <None Update=".env" CopyToOutputDirectory="PreserveNewest" Condition="Exists('.env')" />
  </ItemGroup>

</Project>
`,
  });

  files.push({ path: 'connections.json', content: JSON.stringify(built.connectionsFile, null, 2) + '\n' });
  files.push({ path: '.env.example', content: envExample(built) });
  files.push({ path: '.gitignore', content: '.env\nbin/\nobj/\n' });

  const hasSecrets = Object.keys(built.secretEnv).length > 0;
  files.push({
    path: 'README.md',
    content: `# ${project.name}

${project.description ? project.description + '\n\n' : ''}Generated by AIUI. Requires the .NET SDK 8 or newer.

## Run

\`\`\`bash
${hasSecrets ? 'cp .env.example .env   # then fill in the secrets\n' : ''}dotnet run
\`\`\`

| Option | Meaning |
|---|---|
| \`dotnet run -- --once\` | Run a single time and exit, whatever the trigger is |
| \`dotnet run -- --input '{"key": "value"}'\` | Data for the trigger (or \`--input @file.json\`) |
| \`dotnet run -- --events\` | Print machine-readable events instead of log lines |

## Steps

${describeFlow(built)}

## Files

| File | Purpose |
|---|---|
| \`Workflow.cs\` | The steps, their settings and how they are linked |
| \`Steps/\` | The code behind each kind of step |
| \`Runtime/\` | The engine that runs the workflow |
| \`connections.json\` | Connection settings; secrets are read from the environment |
| \`.env.example\` | The secrets this project needs |
`,
  });
  return files;
}

export const csharpProjectFolder = (name: string) => safeName(name, 'pascal');
